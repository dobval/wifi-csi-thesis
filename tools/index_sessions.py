#!/usr/bin/env python3
"""Regenerate sessions/INDEX.md from the data/ folders.

    python3 tools/index_sessions.py

The index is the one place that lists every capture, so nobody has to open twelve
session.md files to find out what exists. It reads only the committed metadata, so
it works on a fresh clone with no raw data present.
"""
from __future__ import annotations

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "sessions", "INDEX.md")


def parse_session_md(path: str) -> dict:
    out = {}
    if not os.path.isfile(path):
        return out
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|", line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip("` ")
        out[key] = val
    return out


def requested_seconds(md: dict) -> float:
    """Pull the requested duration out of session.md ("600 s" or open-ended)."""
    m = re.search(r"(\d+)\s*s", md.get("Duration requested", ""))
    return float(m.group(1)) if m else 0.0


def classify(name: str, stats: dict | None, md: dict) -> str:
    if "ABORTED" in name:
        return "**aborted**"
    if stats is None:
        return "**incomplete**"
    if "_PARTIAL" in name:
        return "**partial**"
    # Older sessions predate csi_span_s; fall back to elapsed time.
    span = stats.get("csi_span_s") or stats.get("elapsed_s") or 0
    want = requested_seconds(md)
    if want and span < 0.95 * want:
        return "**partial**"
    return "complete"


def main() -> int:
    rows = []
    for name in sorted(os.listdir(DATA)):
        d = os.path.join(DATA, name)
        if not os.path.isdir(d):
            continue
        md = parse_session_md(os.path.join(d, "session.md"))
        stats = None
        sp = os.path.join(d, "csi_stats.json")
        if os.path.isfile(sp):
            try:
                stats = json.load(open(sp))
            except ValueError:
                stats = None

        sched = os.path.join(d, "schedule.csv")
        conds = ""
        if os.path.isfile(sched):
            seen, order = set(), []
            for line in open(sched, encoding="utf-8"):
                parts = line.strip().split(",")
                if len(parts) >= 2 and parts[0] != "block":
                    c = parts[1]
                    if c not in seen:
                        seen.add(c)
                        order.append(c)
            conds = " / ".join(order)

        rows.append({
            "folder": name,
            "started": md.get("Started (UTC)", ""),
            "label": md.get("Label", ""),
            "conds": conds,
            "span": (stats or {}).get("csi_span_s") or (stats or {}).get("elapsed_s") or 0.0,
            "rows": (stats or {}).get("csi_rows") or 0,
            "status": classify(name, stats, md),
            "dist": md.get("Node → AP distance", ""),
        })

    rows.sort(key=lambda r: r["folder"])

    lines = [
        "# Session index",
        "",
        "Generated by `python3 tools/index_sessions.py` — do not edit by hand.",
        "",
        "One row per folder in `data/`. Raw captures (`csi.csv`) are **not** stored in",
        "git; what is versioned here is the protocol, the integrity manifest and the",
        "1 Hz clock sidecar. A folder whose `csi.csv` is absent on your machine is",
        "still a valid record of a session that happened.",
        "",
        "| session | started (UTC) | label | conditions | span | rows | node→AP | status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['folder']}` | {r['started']} | `{r['label']}` | "
            f"{('`' + r['conds'] + '`') if r['conds'] else '—'} | "
            f"{r['span']:.0f} s | {r['rows']:,} | {r['dist'] or '—'} | {r['status']} |"
        )
    lines += [
        "",
        "## Reading the status",
        "",
        "| status | meaning |",
        "|---|---|",
        "| complete | finalised, span matches the requested duration |",
        "| partial | finalised but stopped early — later blocks have no valid cues |",
        "| aborted | killed before finalising — the subject was not following the schedule |",
        "| incomplete | no `csi_stats.json`: the capture never started or never stopped cleanly |",
        "",
        "Only `complete` sessions may be used as labelled data. `partial` sessions are",
        "usable up to the block where the cue loop died, and must be analysed with",
        "`probe_alt.py --blocks 1-N`.",
    ]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(rows)} sessions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
